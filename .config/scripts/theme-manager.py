# 4. FILE WRITERS & APP UPDATERS
# ==============================================================================
def write_file(path: Path, content: str, dry_run: bool = False):
    """
    Safely writes text content to a destination file, ensuring parent dirs exist.
    """
    if dry_run:
        print(f"  [dry-run] Would write -> {path}")
        return

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def update_herdr_config(theme_name: str, dry_run: bool = False):
    """
    Updates the theme name field under [theme] in ~/.config/herdr/config.toml.
    Preserves all existing comments and settings.
    """
    herdr_path = CONFIG_DIR / "herdr" / "config.toml"
    if not herdr_path.exists():
        return

    if dry_run:
        print(f"  [dry-run] Would update herdr theme -> '{theme_name}' in {herdr_path}")
        return

    try:
        content = herdr_path.read_text(encoding="utf-8")
        # Matches 'name = "..."' under the [theme] section
        pattern = r'(name\s*=\s*")[^"]*(")'
        new_content = re.sub(pattern, rf'\g<1>{theme_name}\g<2>', content, count=1)
        herdr_path.write_text(new_content, encoding="utf-8")
    except Exception as err:
        print(f"[Warning] Could not update herdr config: {err}", file=sys.stderr)


def update_ohmyposh(palette_file_name: str, dry_run: bool = False):
    """
    Combines the theme's OhMyPosh palette with bar.toml into currentTheme.toml.
    """
    omp_dir = CONFIG_DIR / "OhMyPosh" / "Themes"
    palette_file = omp_dir / "themes" / palette_file_name
    layout_file = omp_dir / "bar.toml"
    target_file = omp_dir / "currentTheme.toml"

    if dry_run:
        print(f"  [dry-run] Would merge OhMyPosh palette {palette_file} -> {target_file}")
        return

    if palette_file.exists() and layout_file.exists():
        try:
            palette_content = palette_file.read_text(encoding="utf-8")
            layout_content = layout_file.read_text(encoding="utf-8")
            target_file.write_text(palette_content + "\n" + layout_content, encoding="utf-8")
        except Exception as err:
            print(f"[Warning] Could not update OhMyPosh: {err}", file=sys.stderr)


# ==============================================================================
# 5. LIVE PROCESS RELOADER (Broadcasts reloads without app restarts)
# ==============================================================================
def broadcast_reloads(nvim_colorscheme: str, dry_run: bool = False):
    """
    Sends signals or commands to running applications so they refresh their styling.
    Fails gracefully if an application is not currently running.
    """
    if dry_run:
        print("  [dry-run] Would signal running apps: Waybar, Swaync, Hyprland, Tmux, Neovim")
        return

    # 1. Waybar: Waybar reloads CSS on SIGUSR2
    try:
        subprocess.run(["pkill", "-USR2", "-x", "waybar"], check=False, stderr=subprocess.DEVNULL)
    except Exception:
        pass

    # 2. Swaync: swaync-client commands reload CSS & restart widget
    try:
        subprocess.run(["swaync-client", "-R"], check=False, stderr=subprocess.DEVNULL)
        subprocess.run(["swaync-client", "-rs"], check=False, stderr=subprocess.DEVNULL)
    except Exception:
        pass

    # 3. Hyprland: hyprctl reload re-evaluates lua config and border colors
    try:
        subprocess.run(["hyprctl", "reload"], check=False, stderr=subprocess.DEVNULL)
    except Exception:
        pass

    # 4. Tmux: Re-sources ~/.tmux.conf for all active sessions
    try:
        check_tmux = subprocess.run(["tmux", "ls"], capture_output=True, check=False)
        if check_tmux.returncode == 0:
            subprocess.run(["tmux", "source-file", str(HOME / ".tmux.conf")], check=False, stderr=subprocess.DEVNULL)
    except Exception:
        pass

    # 5. Neovim: Loops through active RPC sockets in /run/user/<UID>/nvim.*
    uid = os.getuid()
    nvim_sockets = glob.glob(f"/run/user/{uid}/nvim.*") + glob.glob(f"/tmp/nvim.{os.environ.get('USER', 'luffy')}/*/0")
    for sock in nvim_sockets:
        if os.path.exists(sock):
            try:
                cmd = f"<Esc>:colorscheme {nvim_colorscheme}<CR>"
                subprocess.run(["nvim", "--server", sock, "--remote-send", cmd], check=False, stderr=subprocess.DEVNULL)
            except Exception:
                pass

    # 6. Ghostty: Sends SIGUSR2 to reload configuration live
    try:
        subprocess.run(["pkill", "-USR2", "-x", "ghostty"], check=False, stderr=subprocess.DEVNULL)
    except Exception:
        pass

    # 7. Oh-My-Posh: Clears cache so prompt fetches new palette
    try:
        subprocess.run(["oh-my-posh", "cache", "clear"], check=False, stderr=subprocess.DEVNULL, stdout=subprocess.DEVNULL)
    except Exception:
        pass


# ==============================================================================
# 6. TERMINAL PALETTE PREVIEWER (ANSI 24-bit Truecolor)
# ==============================================================================
def hex_to_rgb(hex_code: str) -> tuple[int, int, int]:
    """Converts a hex color code (e.g. #2e3440 or #fff) to an (R, G, B) tuple."""
    hex_code = hex_code.lstrip("#")
    if len(hex_code) == 3:
        hex_code = "".join([c * 2 for c in hex_code])
    if len(hex_code) >= 6:
        return int(hex_code[0:2], 16), int(hex_code[2:4], 16), int(hex_code[4:6], 16)
    return 128, 128, 128


def preview_theme_palette(theme_id: str, theme_data: dict, is_active: bool = False):
    """
    Renders visual ANSI Truecolor swatches of the theme palette in the terminal.
    """
    name = theme_data["display_name"]
    desc = theme_data.get("description", "")
    colors = theme_data.get("colors", {})

    status_tag = "\033[1;32m[Active]\033[0m" if is_active else ""
    print(f"\n\033[1m● {name}\033[0m ({theme_id}) {status_tag}")
    if desc:
        print(f"  \033[38;5;245m{desc}\033[0m")
    print("  " + "─" * 48)

    # Key color tokens to display
    key_tokens = ["bg", "fg", "accent", "highlight", "surface", "muted", "urgent", "warning", "success"]
    for token in key_tokens:
        val = colors.get(token)
        if not val or not val.startswith("#"):
            continue
        r, g, b = hex_to_rgb(val)
        # 24-bit truecolor background escape sequence: \033[48;2;R;G;Bm
        color_block = f"\033[48;2;{r};{g};{b}m    \033[0m"
        print(f"  {color_block}  \033[1m{token:<10}\033[0m : {val}")
    print()


# ==============================================================================
# 7. MAIN LOGIC & COMMAND DISPATCHER
# ==============================================================================
def apply_theme(
    theme_id: str,
    dry_run: bool = False,
    no_reload: bool = False,
    only_apps: list[str] | None = None,
    silent: bool = False,
):
    """
    Main orchestrator: loads the theme, writes all target files, and triggers reloads.
    """
    data = load_themes_data()
    themes = data.get("themes", {})

    if theme_id not in themes:
        available = ", ".join(themes.keys())
        sys.exit(f"[Error] Unknown theme '{theme_id}'.\nAvailable themes: {available}")

    theme = themes[theme_id]
    colors = theme["colors"]
    apps = theme["apps"]

    def should_update(app_name: str) -> bool:
        return (not only_apps) or (app_name in only_apps)

    if not silent:
        mode = " (Dry Run)" if dry_run else ""
        print(f"\nApplying theme: \033[1m{theme['display_name']}\033[0m ({theme_id}){mode}...")

    # 1. Global CSS (Waybar, Swaync, Wlogout, Walker)
    if should_update("css"):
        write_file(GLOBAL_CSS_FILE, generate_global_css(colors), dry_run)

    # 2. Ghostty
    if should_update("ghostty"):
        write_file(CONFIG_DIR / "ghostty" / "current-theme.conf", generate_ghostty_conf(apps), dry_run)

    # 3. Tmux
    if should_update("tmux"):
        write_file(CONFIG_DIR / "tmux" / "current-theme.conf", generate_tmux_conf(apps["tmux"]), dry_run)

    # 4. Neovim
    if should_update("nvim"):
        write_file(CONFIG_DIR / "nvim" / "lua" / "current-theme.lua", generate_nvim_lua(apps), dry_run)

    # 5. Hyprland
    if should_update("hypr"):
        write_file(CONFIG_DIR / "hypr" / "colors.lua", generate_hypr_colors(colors), dry_run)

    # 6. Yazi
    if should_update("yazi"):
        write_file(CONFIG_DIR / "yazi" / "theme.toml", generate_yazi_conf(apps), dry_run)

    # 7. Zsh & CLI tools
    if should_update("zsh"):
        write_file(CONFIG_DIR / "zsh" / "current-theme.zsh", generate_zsh_styles(apps, apps["fzf"]), dry_run)

    # 8. Herdr & OhMyPosh
    if should_update("herdr"):
        update_herdr_config(apps["herdr"], dry_run)
    if should_update("ohmyposh"):
        update_ohmyposh(apps["ohmyposh_palette"], dry_run)

    # 9. Update state file
    if not dry_run:
        set_current_theme_name(theme_id)

    # 10. Process Reloads
    if not no_reload and not dry_run:
        broadcast_reloads(apps["nvim"], dry_run=False)

    # 11. Desktop Notification
    if not dry_run and not silent:
        try:
            subprocess.run([
                "notify-send",
                "-a", "Theme Manager",
                "-i", "preferences-desktop-theme",
                f"Theme: {theme['display_name']}",
                f"{theme.get('description', '')}"
            ], check=False, stderr=subprocess.DEVNULL)
        except Exception:
            pass

    if not silent:
        print(f"✓ Theme \033[1m{theme['display_name']}\033[0m applied successfully.\n")


def list_themes(json_format: bool = False, names_only: bool = False, verbose: bool = False):
    """
    Lists available themes in plain text, raw IDs, or structured JSON.
    """
    data = load_themes_data()
    themes = data.get("themes", {})
    current = get_current_theme_name()

    if json_format:
        output = []
        for theme_id, info in themes.items():
            output.append({
                "id": theme_id,
                "name": info["display_name"],
                "icon": info.get("icon", "preferences-desktop-theme"),
                "description": info.get("description", ""),
                "is_current": (theme_id == current),
                "colors": info.get("colors", {})
            })
        print(json.dumps(output, indent=2))
        return

    if names_only:
        for theme_id in themes.keys():
            print(theme_id)
        return

    print("\n\033[1mAvailable Themes:\033[0m")
    for theme_id, info in themes.items():
        is_active = (theme_id == current)
        marker = "\033[1;32m●\033[0m" if is_active else "○"
        active_label = " \033[1;32m(active)\033[0m" if is_active else ""
        desc = f" - {info.get('description', '')}" if verbose else ""
        print(f"  {marker} \033[1m{theme_id:<14}\033[0m {info['display_name']}{desc}{active_label}")
    print()


def main():
    """
    CLI Entrypoint and Argument Parser.
    """
    # Shorthand support: if first argument is a theme name, treat as 'apply <name>'
    valid_commands = {"apply", "switch", "set", "list", "ls", "current", "status", "preview", "view", "reload", "r", "-h", "--help"}
    if len(sys.argv) > 1 and sys.argv[1] not in valid_commands and not sys.argv[1].startswith("-"):
        sys.argv.insert(1, "apply")

    parser = argparse.ArgumentParser(
        prog="theme-switcher",
        description="Unified Dotfiles Theme Engine & Colorscheme Switcher",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  theme-switcher apply nord             # Apply the Nord theme
  theme-switcher catppuccin             # Shorthand for applying a theme
  theme-switcher apply nord --dry-run   # Test without making changes
  theme-switcher list                   # List all available themes
  theme-switcher list --json            # Output theme list as JSON
  theme-switcher current                # Show active theme
  theme-switcher preview catppuccin     # Show color swatches in terminal
  theme-switcher reload                 # Re-send reload signals to apps
        """
    )

    subparsers = parser.add_subparsers(dest="command", help="Command to execute")

    # Command: apply
    apply_parser = subparsers.add_parser("apply", aliases=["switch", "set"], help="Apply a theme")
    apply_parser.add_argument("theme", nargs="?", help="Theme ID to apply (e.g. nord, catppuccin)")
    apply_parser.add_argument("--dry-run", action="store_true", help="Simulate changes without modifying files")
    apply_parser.add_argument("--no-reload", action="store_true", help="Write files but skip process reloads")
    apply_parser.add_argument("--only", type=lambda s: s.split(","), help="Comma-separated list of apps to update")
    apply_parser.add_argument("--silent", action="store_true", help="Suppress terminal messages and notifications")

    # Command: list
    list_parser = subparsers.add_parser("list", aliases=["ls"], help="List available themes")
    list_parser.add_argument("--json", action="store_true", help="Format output as JSON")
    list_parser.add_argument("--names-only", action="store_true", help="Print only theme IDs, one per line")
    list_parser.add_argument("--verbose", "-v", action="store_true", help="Show descriptions and extra metadata")

    # Command: current
    subparsers.add_parser("current", aliases=["status"], help="Print currently active theme")

    # Command: preview
    preview_parser = subparsers.add_parser("preview", aliases=["view"], help="Preview theme color palette in terminal")
    preview_parser.add_argument("theme", nargs="?", help="Theme to preview (defaults to active theme)")

    # Command: reload
    subparsers.add_parser("reload", aliases=["r"], help="Re-broadcast live reload signals to apps")

    args, unknown = parser.parse_known_args()

    # Handle shorthand: theme-switcher <name> directly
    if not args.command:
        if unknown:
            theme_id = unknown[0]
            apply_theme(theme_id)
            return
        list_themes()
        return

    if args.command in ("apply", "switch", "set"):
        target_theme = args.theme or (unknown[0] if unknown else None)
        if not target_theme:
            sys.exit("[Error] Please specify a theme name. Run 'theme-switcher list' to see available themes.")
        apply_theme(
            theme_id=target_theme,
            dry_run=args.dry_run,
            no_reload=args.no_reload,
            only_apps=args.only,
            silent=args.silent,
        )

    elif args.command in ("list", "ls"):
        list_themes(json_format=args.json, names_only=args.names_only, verbose=args.verbose)

    elif args.command in ("current", "status"):
        print(get_current_theme_name())

    elif args.command in ("preview", "view"):
        data = load_themes_data()
        themes = data.get("themes", {})
        active = get_current_theme_name()
        target = args.theme or active
        if target not in themes:
            sys.exit(f"[Error] Theme '{target}' not found.")
        preview_theme_palette(target, themes[target], is_active=(target == active))

    elif args.command in ("reload", "r"):
        data = load_themes_data()
        active = get_current_theme_name()
        theme = data.get("themes", {}).get(active)
        if not theme:
            sys.exit(f"[Error] Active theme '{active}' not found in configuration.")
        print(f"Reloading apps for active theme: {theme['display_name']}...")
        broadcast_reloads(theme["apps"]["nvim"], dry_run=False)
        print("✓ Reload signals sent.")


if __name__ == "__main__":
    main()
