# 7. MAIN LOGIC & COMMAND DISPATCHER
# ==============================================================================
def apply_theme_object(
    theme_id: str,
    theme: dict,
    dry_run: bool = False,
    no_reload: bool = False,
    only_apps: list[str] | None = None,
    silent: bool = False,
):
    """
    Core orchestrator: writes all target files from a theme dict and triggers reloads.
    """
    colors = theme["colors"]
    apps = theme["apps"]

    def should_update(app_name: str) -> bool:
        return (not only_apps) or (app_name in only_apps)

    if not silent:
        mode = " (Dry Run)" if dry_run else ""
        print(f"\nApplying theme: \033[1m{theme['display_name']}\033[0m ({theme_id}){mode}...")

    # 1. Global CSS (Waybar, Swaync, Wlogout, Walker)
    if should_update("css"):
        write_file(GLOBAL_CSS_FILE, generate_global_css(colors), dry_run)

    # 2. Ghostty
    if should_update("ghostty"):
        write_file(CONFIG_DIR / "ghostty" / "current-theme.conf", generate_ghostty_conf(apps), dry_run)

    # 3. Tmux
    if should_update("tmux"):
        write_file(CONFIG_DIR / "tmux" / "current-theme.conf", generate_tmux_conf(apps["tmux"]), dry_run)

    # 4. Neovim
    if should_update("nvim"):
        write_file(CONFIG_DIR / "nvim" / "lua" / "current-theme.lua", generate_nvim_lua(apps), dry_run)

    # 5. Hyprland
    if should_update("hypr"):
        write_file(CONFIG_DIR / "hypr" / "colors.lua", generate_hypr_colors(colors), dry_run)

    # 6. Yazi
    if should_update("yazi"):
        write_file(CONFIG_DIR / "yazi" / "theme.toml", generate_yazi_conf(apps), dry_run)

    # 7. Zsh & CLI tools
    if should_update("zsh"):
        write_file(CONFIG_DIR / "zsh" / "current-theme.zsh", generate_zsh_styles(apps, apps["fzf"]), dry_run)

    # 8. Herdr & OhMyPosh
    if should_update("herdr"):
        update_herdr_config(apps["herdr"], dry_run)
    if should_update("ohmyposh"):
        update_ohmyposh(apps["ohmyposh_palette"], dry_run)

    # 9. GTK (3.0 & 4.0 / Libadwaita)
    if should_update("gtk"):
        update_gtk(
            gtk_theme=apps.get("gtk_theme", "Nordic"),
            cursor_theme=apps.get("cursor_theme", "Nordzy-catppuccin-mocha-dark"),
            icon_theme=apps.get("icon_theme", "Papirus-Dark"),
            dry_run=dry_run,
        )

    # 10. QT (qt5ct, qt6ct, Kvantum)
    if should_update("qt"):
        update_qt(
            colors=colors,
            kvantum_theme=apps.get("kvantum", "KvDark"),
            dry_run=dry_run,
        )

    # 11. Update state file
    if not dry_run:
        set_current_theme_name(theme_id)
        try:
            PALETTE_JSON_FILE.write_text(json.dumps(theme, indent=2), encoding="utf-8")
        except Exception:
            pass

    # 12. Process Reloads
    if not no_reload and not dry_run:
        broadcast_reloads(apps["nvim"], dry_run=False)

    # 13. Desktop Notification
    if not dry_run and not silent:
        try:
            subprocess.run([
                "notify-send",
                "-a", "Theme Manager",
                "-i", "preferences-desktop-theme",
                f"Theme: {theme['display_name']}",
                f"{theme.get('description', '')}"
            ], check=False, stderr=subprocess.DEVNULL)
        except Exception:
            pass

    if not silent:
        print(f"✓ Theme \033[1m{theme['display_name']}\033[0m applied successfully.\n")


def apply_theme(
    theme_id: str,
    dry_run: bool = False,
    no_reload: bool = False,
    only_apps: list[str] | None = None,
    silent: bool = False,
):
    """
    Loads a theme by ID from themes.json and applies it.
    """
    data = load_themes_data()
    themes = data.get("themes", {})

    if theme_id not in themes:
        available = ", ".join(themes.keys())
        sys.exit(f"[Error] Unknown theme '{theme_id}'.\nAvailable themes: {available}")

    apply_theme_object(
        theme_id=theme_id,
        theme=themes[theme_id],
        dry_run=dry_run,
        no_reload=no_reload,
        only_apps=only_apps,
        silent=silent,
    )


def detect_theme_from_path(wallpaper_path: Path) -> str | None:
    """
    Checks if a wallpaper image belongs to a predefined theme directory or has theme tags.
    """
    data = load_themes_data()
    dirs_map = data.get("wallpaper_dirs", {})

    # 1. Check folder names in path
    for part in wallpaper_path.parts:
        part_lower = part.lower()
        if part_lower in dirs_map:
            return dirs_map[part_lower]

    # 2. Check filename keywords
    filename_lower = wallpaper_path.name.lower()
    for keyword, theme_id in dirs_map.items():
        if keyword in filename_lower:
            return theme_id

    return None


def matugen_extract_palette(wallpaper_path: Path) -> dict | None:
    """
    Extracts a dynamic, vibrant Material Design dark palette from an image using matugen.
    Uses --prefer saturation and -t scheme-vibrant to ensure colors are rich and faithful
    to the wallpaper rather than desaturated dull grays.
    """
    if not shutil.which("matugen"):
        return None

    cmd = [
        "matugen", "image", str(wallpaper_path),
        "--prefer", "saturation",
        "-t", "scheme-vibrant",
        "--mode", "dark",
        "--json", "hex",
    ]
    try:
        res = subprocess.run(cmd, capture_output=True, text=True, check=False)
        if res.returncode != 0:
            # Fallback without scheme-vibrant if unsupported
            cmd_fallback = [
                "matugen", "image", str(wallpaper_path),
                "--prefer", "saturation",
                "--mode", "dark",
                "--json", "hex",
            ]
            res = subprocess.run(cmd_fallback, capture_output=True, text=True, check=False)
            if res.returncode != 0:
                return None

        data = json.loads(res.stdout)
        colors = data.get("colors", {})
        if not colors:
            return None

        def get_c(key, default="#ffffff"):
            node = colors.get(key, {})
            if isinstance(node, dict):
                return node.get("default", {}).get("color", default)
            return default

        # Vibrant primary accent directly extracted from wallpaper's most colorful feature
        accent = get_c("primary", "#89b4fa")
        # Use primary for highlight so active workspaces/buttons pop with the wallpaper's main color
        highlight = accent
        warning = get_c("tertiary", "#f9e2af")
        urgent = get_c("error", "#f38ba8")
        success = get_c("primary_fixed", "#a6e3a1")
        muted = get_c("outline", "#6c7086")

        # In scheme-vibrant, surface_dim and surface_containers inherit the hue of the wallpaper
        # giving a rich tinted dark background instead of flat neutral gray
        bg = get_c("surface_dim", get_c("background", "#121212"))
        fg = get_c("on_surface", get_c("on_background", "#e0e0e0"))
        dark_9 = bg
        dark_8 = get_c("surface_container_low", get_c("surface_container", "#1e1e1e"))
        dark_7 = get_c("surface_container", "#252525")
        dark_5 = get_c("surface_container_high", "#333333")
        surface = dark_7
        surface_variant = dark_5

        r_acc, g_acc, b_acc = hex_to_rgb(accent)
        r_mut, g_mut, b_mut = hex_to_rgb(muted)

        return {
            "display_name": f"Matugen ({wallpaper_path.stem})",
            "icon": "image",
            "description": f"Dynamic vibrant palette from {wallpaper_path.name}",
            "colors": {
                "bg": bg,
                "fg": fg,
                "accent": accent,
                "highlight": highlight,
                "surface": surface,
                "surface_variant": surface_variant,
                "muted": muted,
                "urgent": urgent,
                "error": urgent,
                "warning": warning,
                "success": success,
                "dark_9": dark_9,
                "dark_8": dark_8,
                "dark_7": dark_7,
                "dark_5": dark_5,
                "white": "#ffffff",
                "border_active": f"rgba({r_acc}, {g_acc}, {b_acc}, 0.9)",
                "border_inactive": f"rgba({r_mut}, {g_mut}, {b_mut}, 0.7)",
            },
            "apps": {
                "ghostty": "Catppuccin Mocha",
                "nvim": "catppuccin-mocha",
                "herdr": "catppuccin",
                "bat": "base16",
                "yazi_flavor": "catppuccin-mocha",
                "ohmyposh_palette": "catppuccin.toml",
                "gtk_theme": "Nordic",
                "cursor_theme": "Nordzy-catppuccin-mocha-dark",
                "icon_theme": "Papirus-Dark",
                "kvantum": "KvDark",
                "tmux": {
                    "gray_light": fg,
                    "gray_medium": surface_variant,
                    "gray_dark": bg,
                    "green_soft": get_c("primary_fixed", "#a6e3a1"),
                    "blue_muted": highlight,
                    "cyan_soft": accent,
                },
                "fzf": {
                    "bg_plus": surface,
                    "bg": bg,
                    "spinner": accent,
                    "hl": urgent,
                    "fg": fg,
                    "header": urgent,
                    "info": highlight,
                    "pointer": accent,
                    "marker": accent,
                    "fg_plus": fg,
                    "prompt": accent,
                    "hl_plus": urgent,
                    "selected_bg": surface_variant,
                    "border": muted,
                },
            },
        }
    except Exception as err:
        print(f"[Warning] Matugen extraction failed: {err}", file=sys.stderr)
        return None


def handle_wallpaper(wallpaper_path_str: str):
    """
    Sets the wallpaper via awww, detects predefined themes or extracts with matugen,
    and applies the theme across all applications seamlessly.
    """
    wp_path = Path(wallpaper_path_str).expanduser().resolve()
    if not wp_path.exists():
        sys.exit(f"[Error] Wallpaper file not found: {wp_path}")

    # 1. Trigger wallpaper transition using awww
    if shutil.which("awww"):
        try:
            subprocess.run([
                "awww", "img",
                "--transition-type", "random",
                "--transition-fps", "144",
                str(wp_path),
            ], check=False, stderr=subprocess.DEVNULL)
        except Exception:
            pass

    # 2. Check if wallpaper belongs to a predefined theme directory
    detected = detect_theme_from_path(wp_path)
    if detected:
        apply_theme(detected, silent=True)
        return

    # 3. Fallback: Generate dynamic palette with Matugen
    dynamic_theme = matugen_extract_palette(wp_path)
    if dynamic_theme:
        apply_theme_object("dynamic", dynamic_theme, silent=True)


def list_themes(json_format: bool = False, names_only: bool = False, verbose: bool = False):
    """
    Lists available themes in plain text, raw IDs, or structured JSON.
    """
    data = load_themes_data()
    themes = data.get("themes", {})
    current = get_current_theme_name()

    if json_format:
        output = []
        for theme_id, info in themes.items():
            output.append({
                "id": theme_id,
                "name": info["display_name"],
                "icon": info.get("icon", "preferences-desktop-theme"),
                "description": info.get("description", ""),
                "is_current": (theme_id == current),
                "colors": info.get("colors", {})
            })
        print(json.dumps(output, indent=2))
        return

    if names_only:
        for theme_id in themes.keys():
            print(theme_id)
        return

    print("\n\033[1mAvailable Themes:\033[0m")
    for theme_id, info in themes.items():
        is_active = (theme_id == current)
        marker = "\033[1;32m●\033[0m" if is_active else "○"
        active_label = " \033[1;32m(active)\033[0m" if is_active else ""
        desc = f" - {info.get('description', '')}" if verbose else ""
        print(f"  {marker} \033[1m{theme_id:<14}\033[0m {info['display_name']}{desc}{active_label}")
    print()


def pick_theme():
    """
    Launches an interactive fuzzy picker with live Truecolor palette preview.
    Uses 'tv' (Television) by default, or falls back to 'fzf'.
    """
    data = load_themes_data()
    themes = data.get("themes", {})
    if not themes:
        sys.exit("[Error] No themes configured in themes.json.")

    selected_theme = None

    # 1. Try 'tv' (Television) with live preview panel
    if shutil.which("tv"):
        try:
            cmd = [
                "tv",
                "-s", "theme-switcher list --names-only",
                "-p", "theme-switcher preview {}",
            ]
            res = subprocess.run(cmd, stdout=subprocess.PIPE, text=True, check=False)
            if res.returncode == 0 and res.stdout.strip():
                selected_theme = res.stdout.strip().splitlines()[-1].strip()
        except Exception:
            selected_theme = None

    # 2. Fallback to 'fzf' if tv is not available or errored
    if not selected_theme and shutil.which("fzf"):
        try:
            fzf_cmd = [
                "fzf",
                "--reverse",
                "--prompt=Select Theme: ",
                "--preview=theme-switcher preview {}",
            ]
            data_proc = subprocess.run(
                ["theme-switcher", "list", "--names-only"],
                stdout=subprocess.PIPE,
                text=True,
                check=False
            )
            res = subprocess.run(
                fzf_cmd,
                input=data_proc.stdout,
                stdout=subprocess.PIPE,
                text=True,
                check=False
            )
            if res.returncode == 0 and res.stdout.strip():
                selected_theme = res.stdout.strip()
        except Exception:
            selected_theme = None

    if selected_theme:
        if selected_theme in themes:
            apply_theme(selected_theme)
        else:
            sys.exit(f"[Error] Selected theme '{selected_theme}' not recognized.")


def main():
    """
    CLI Entrypoint and Argument Parser.
    """
    # Shorthand support: if first argument is a theme name, treat as 'apply <name>'
    valid_commands = {"apply", "switch", "set", "list", "ls", "current", "status", "preview", "view", "reload", "r", "pick", "p", "wallpaper", "wall", "wp", "-h", "--help"}
    if len(sys.argv) > 1 and sys.argv[1] not in valid_commands and not sys.argv[1].startswith("-"):
        sys.argv.insert(1, "apply")

    parser = argparse.ArgumentParser(
        prog="theme-switcher",
        description="Unified Dotfiles Theme Engine & Colorscheme Switcher",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  theme-switcher                        # Interactive picker (uses tv / fzf)
  theme-switcher pick                   # Interactive picker with live preview
  theme-switcher wallpaper <image>      # Set wallpaper and adapt theme
  theme-switcher apply nord             # Apply the Nord theme
  theme-switcher catppuccin             # Shorthand for applying a theme
  theme-switcher apply nord --dry-run   # Test without making changes
  theme-switcher list                   # List all available themes
  theme-switcher list --json            # Output theme list as JSON
  theme-switcher current                # Show active theme
  theme-switcher preview catppuccin     # Show color swatches in terminal
  theme-switcher reload                 # Re-send reload signals to apps
        """
    )

    subparsers = parser.add_subparsers(dest="command", help="Command to execute")

    # Command: pick
    subparsers.add_parser("pick", aliases=["p"], help="Interactive fuzzy theme picker with live preview (tv/fzf)")

    # Command: wallpaper
    wallpaper_parser = subparsers.add_parser("wallpaper", aliases=["wall", "wp"], help="Set wallpaper and adapt theme (curated or matugen)")
    wallpaper_parser.add_argument("path", help="Path to wallpaper image file")

    # Command: apply
    apply_parser = subparsers.add_parser("apply", aliases=["switch", "set"], help="Apply a theme")
    apply_parser.add_argument("theme", nargs="?", help="Theme ID to apply (e.g. nord, catppuccin)")
    apply_parser.add_argument("--dry-run", action="store_true", help="Simulate changes without modifying files")
    apply_parser.add_argument("--no-reload", action="store_true", help="Write files but skip process reloads")
    apply_parser.add_argument("--only", type=lambda s: s.split(","), help="Comma-separated list of apps to update")
    apply_parser.add_argument("--silent", action="store_true", help="Suppress terminal messages and notifications")

    # Command: list
    list_parser = subparsers.add_parser("list", aliases=["ls"], help="List available themes")
    list_parser.add_argument("--json", action="store_true", help="Format output as JSON")
    list_parser.add_argument("--names-only", action="store_true", help="Print only theme IDs, one per line")
    list_parser.add_argument("--verbose", "-v", action="store_true", help="Show descriptions and extra metadata")

    # Command: current
    subparsers.add_parser("current", aliases=["status"], help="Print currently active theme")

    # Command: preview
    preview_parser = subparsers.add_parser("preview", aliases=["view"], help="Preview theme color palette in terminal")
    preview_parser.add_argument("theme", nargs="?", help="Theme to preview (defaults to active theme)")

    # Command: reload
    subparsers.add_parser("reload", aliases=["r"], help="Re-broadcast live reload signals to apps")

    args, unknown = parser.parse_known_args()

    # Handle shorthand: theme-switcher <name> directly or interactive pick
    if not args.command:
        if unknown:
            theme_id = unknown[0]
            apply_theme(theme_id)
            return
        if sys.stdin.isatty():
            pick_theme()
            return
        list_themes()
        return

    if args.command in ("pick", "p"):
        pick_theme()

    elif args.command in ("apply", "switch", "set"):
        target_theme = args.theme or (unknown[0] if unknown else None)
        if not target_theme:
            sys.exit("[Error] Please specify a theme name. Run 'theme-switcher list' to see available themes.")
        apply_theme(
            theme_id=target_theme,
            dry_run=args.dry_run,
            no_reload=args.no_reload,
            only_apps=args.only,
            silent=args.silent,
        )

    elif args.command in ("list", "ls"):
        list_themes(json_format=args.json, names_only=args.names_only, verbose=args.verbose)

    elif args.command in ("current", "status"):
        print(get_current_theme_name())

    elif args.command in ("preview", "view"):
        data = load_themes_data()
        themes = data.get("themes", {})
        active = get_current_theme_name()
        target = args.theme or active
        if target == "dynamic" and PALETTE_JSON_FILE.exists():
            try:
                dyn_theme = json.loads(PALETTE_JSON_FILE.read_text(encoding="utf-8"))
                preview_theme_palette("dynamic", dyn_theme, is_active=(target == active))
                return
            except Exception:
                pass
        if target not in themes:
            sys.exit(f"[Error] Theme '{target}' not found.")
        preview_theme_palette(target, themes[target], is_active=(target == active))

    elif args.command in ("reload", "r"):
        data = load_themes_data()
        active = get_current_theme_name()
        if active == "dynamic" and PALETTE_JSON_FILE.exists():
            try:
                theme = json.loads(PALETTE_JSON_FILE.read_text(encoding="utf-8"))
            except Exception:
                theme = None
        else:
            theme = data.get("themes", {}).get(active)

        if not theme:
            sys.exit(f"[Error] Active theme '{active}' not found in configuration.")
        print(f"Reloading apps for active theme: {theme['display_name']}...")
        broadcast_reloads(theme["apps"]["nvim"], dry_run=False)
        print("✓ Reload signals sent.")

    elif args.command in ("wallpaper", "wall", "wp"):
        handle_wallpaper(args.path)


if __name__ == "__main__":
    main()
