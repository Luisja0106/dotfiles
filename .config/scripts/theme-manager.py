def load_themes_data() -> dict:
    """
    Reads and parses the central themes.json file.
    Falls back to checking the dotfiles directory directly if needed.
    """
    if THEMES_JSON.exists():
        target = THEMES_JSON
    else:
        target = DOTFILES / ".config" / "themes" / "themes.json"

    if not target.exists():
        sys.exit(f"[Error] Theme configuration file not found at: {target}")

    try:
        with open(target, "r", encoding="utf-8") as f:
            return json.load(f)
    except json.JSONDecodeError as err:
        sys.exit(f"[Error] Failed to parse JSON in {target}: {err}")


def get_current_theme_name() -> str:
    """
    Returns the identifier of the currently active theme.
    If no theme has been applied yet, defaults to 'nord'.
    """
    if CURRENT_FILE.exists():
        name = CURRENT_FILE.read_text(encoding="utf-8").strip()
        if name:
            return name
    return "nord"


def set_current_theme_name(theme_id: str):
    """
    Saves the active theme identifier to ~/.config/theme-active/current.txt.
    """
    ACTIVE_DIR.mkdir(parents=True, exist_ok=True)
    CURRENT_FILE.write_text(theme_id.strip() + "\n", encoding="utf-8")


