#!/usr/bin/env python3
"""
theme-manager.py
================
Unified Dotfiles Theme Engine & Colorscheme Switcher.

This script manages your system-wide color palette, generates configuration files
for your desktop and terminal applications, and broadcasts live reload signals so
applications update immediately without restarts.

Author: Antigravity & Luffy
"""

import argparse
import glob
import json
import os
import re
import subprocess
import sys
from pathlib import Path

# ==============================================================================
# 1. PATH DEFINITIONS
# ==============================================================================
# All paths are calculated dynamically relative to the user's home directory.
HOME = Path.home()
DOTFILES = HOME / "dotfilesLuffy"
CONFIG_DIR = HOME / ".config"

# Central registry of themes
THEMES_JSON = CONFIG_DIR / "themes" / "themes.json"

# Active state directory (where the active theme name and global CSS live)
ACTIVE_DIR = CONFIG_DIR / "theme-active"
CURRENT_FILE = ACTIVE_DIR / "current.txt"
GLOBAL_CSS_FILE = ACTIVE_DIR / "colors.css"


# ==============================================================================
# 2. THEME LOADING & STATE MANAGEMENT
# ==============================================================================
def load_themes_data() -> dict:
    """
    Reads and parses the central themes.json file.
    Falls back to checking the dotfiles directory directly if needed.
    """
    if THEMES_JSON.exists():
        target = THEMES_JSON
    else:
        target = DOTFILES / ".config" / "themes" / "themes.json"

    if not target.exists():
        sys.exit(f"[Error] Theme configuration file not found at: {target}")

    try:
        with open(target, "r", encoding="utf-8") as f:
            return json.load(f)
    except json.JSONDecodeError as err:
        sys.exit(f"[Error] Failed to parse JSON in {target}: {err}")


def get_current_theme_name() -> str:
    """
    Returns the identifier of the currently active theme.
    If no theme has been applied yet, defaults to 'nord'.
    """
    if CURRENT_FILE.exists():
        name = CURRENT_FILE.read_text(encoding="utf-8").strip()
        if name:
            return name
    return "nord"


def set_current_theme_name(theme_id: str):
    """
    Saves the active theme identifier to ~/.config/theme-active/current.txt.
    """
    ACTIVE_DIR.mkdir(parents=True, exist_ok=True)
    CURRENT_FILE.write_text(theme_id.strip() + "\n", encoding="utf-8")


